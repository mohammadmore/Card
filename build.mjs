// ساخت نسخه‌ی production:  npm install && npm run build
// خروجی: assets/app.js (کامپایل‌شده و minify)، assets/app.css (Tailwind فقط با کلاس‌های استفاده‌شده)،
// assets/icons.js (فقط آیکون‌هایی که در کد استفاده شده‌اند) و نشانی نسخه‌دار فایل‌ها در index.html
import { build } from 'esbuild';
import { execFileSync } from 'node:child_process';
import { copyFileSync, mkdirSync, readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { createHash } from 'node:crypto';
import vm from 'node:vm';

// بسته‌ی «پوستر و استوری» جدا ساخته می‌شود و فقط با کلیک کاربر بارگذاری می‌شود؛ هش محتوایش به app.js داده می‌شود تا نسخه‌ی قدیمی کش نماند
await build({ entryPoints: ['src/poster/entry.jsx'], bundle: true, minify: true, format: 'iife', target: ['es2019'], jsx: 'transform', jsxFactory: 'React.createElement', jsxFragment: 'React.Fragment', outfile: 'assets/poster.js', legalComments: 'none' });
const posterHash = createHash('sha256').update(readFileSync('assets/poster.js')).digest('hex').slice(0, 10);
await build({
  define: { __POSTER_V__: JSON.stringify(posterHash) },
  entryPoints: ['src/app.jsx'],
  bundle: true,
  minify: true,
  format: 'iife',
  target: ['es2019'],
  jsx: 'transform',
  jsxFactory: 'React.createElement',
  jsxFragment: 'React.Fragment',
  outfile: 'assets/app.js',
  legalComments: 'none',
});

execFileSync(process.execPath, ['node_modules/tailwindcss/lib/cli.js', '-i', 'src/styles.css', '-o', 'assets/app.css', '--minify'], { stdio: 'inherit' });
// صفحه‌ی معرفی: دموی کارت (فقط وقتی بازدیدکننده دکمه را بزند بارگذاری می‌شود) و CSS جداگانه‌ی سبک
await build({ entryPoints: ['src/demo.jsx'], bundle: true, minify: true, format: 'iife', target: ['es2019'], jsx: 'transform', jsxFactory: 'React.createElement', jsxFragment: 'React.Fragment', outfile: 'assets/demo.js', legalComments: 'none' });
execFileSync(process.execPath, ['node_modules/tailwindcss/lib/cli.js', '-c', 'tailwind.landing.config.js', '-i', 'src/landing.css', '-o', 'assets/landing.css', '--minify'], { stdio: 'inherit' });

mkdirSync('assets/fonts', { recursive: true });
copyFileSync('node_modules/vazirmatn/fonts/webfonts/Vazirmatn[wght].woff2', 'assets/fonts/Vazirmatn-Variable.woff2');
copyFileSync('node_modules/vazirmatn/OFL.txt', 'assets/fonts/Vazirmatn-OFL.txt');

// --- آیکون‌ها: از کتابخانه‌ی کامل Lucide (۱۹۸۹ آیکون، ۴۰۰ کیلوبایت) فقط نام‌هایی برداشته می‌شوند که در کد آمده‌اند ---
const ctx = {}; vm.createContext(ctx);
vm.runInContext(readFileSync('src/vendor/lucide.full.min.js', 'utf8'), ctx);
const all = ctx.lucide.icons;
const walk = (d) => readdirSync(d, { withFileTypes: true }).flatMap(e => e.isDirectory() ? (e.name === 'vendor' ? [] : walk(`${d}/${e.name}`)) : (/\.(jsx?|mjs)$/.test(e.name) ? [`${d}/${e.name}`] : []));
const source = walk('src').map(f => readFileSync(f, 'utf8')).join('\n');
const names = new Set([...source.matchAll(/['"`]([A-Z][A-Za-z0-9]*)['"`]/g)].map(m => m[1])); // حتی نام‌های تک‌حرفی مثل X
names.add('CloudUpload'); // جایگزین UploadCloud در نسخه‌های جدید Lucide
const icons = {};
for (const n of names) { const key = all[n] ? n : all[n[0].toLowerCase() + n.slice(1)] ? n[0].toLowerCase() + n.slice(1) : null; if (key) icons[key] = all[key]; }
writeFileSync('assets/icons.js', `/* Lucide icons subset (ISC License, https://lucide.dev) — generated by build.mjs */\nwindow.lucide={icons:${JSON.stringify(icons)}};\n`);
console.log(`icons: ${Object.keys(icons).length} of ${Object.keys(all).length}`);
// آیکون‌های صفحه‌ی معرفی به شکل SVG آماده (landing.php آن‌ها را مستقیم در HTML می‌گذارد)
const LANDING_ICONS = { layers: 'Layers', qr: 'QrCode', languages: 'Languages', cube: 'Box', chart: 'ChartColumn', printer: 'Printer', shield: 'ShieldCheck', table: 'Sheet', badge: 'IdCard', ticket: 'Ticket', users: 'Users', school: 'GraduationCap', check: 'Check', x: 'X', phone: 'Phone', mail: 'Mail', send: 'Send', menu: 'Menu', sun: 'Sun', moon: 'Moon', sunmoon: 'SunMoon', arrowL: 'ArrowLeft', arrowR: 'ArrowRight', sparkles: 'Sparkles', message: 'MessageCircle', map: 'MapPin', globe: 'Globe', star: 'Star', clock: 'Clock', upload: 'Upload', wand: 'WandSparkles', quote: 'Quote', chevron: 'ChevronDown', card: 'CreditCard', alert: 'CircleAlert', building: 'Building2', rocket: 'Rocket', palette: 'Palette', zap: 'Zap', heart: 'Heart', award: 'Award', fingerprint: 'Fingerprint', excel: 'FileSpreadsheet', mobile: 'Smartphone', lock: 'Lock', search: 'Search', verified: 'BadgeCheck', camera: 'Camera', film: 'Film' };
const kebab = (k) => k.replace(/([a-z0-9])([A-Z])/g, '$1-$2').toLowerCase();
const landingIcons = {};
for (const [key, name] of Object.entries(LANDING_ICONS)) {
  const node = all[name] || all[name[0].toLowerCase() + name.slice(1)]; if (!node) continue;
  const kids = Array.isArray(node) ? (node[0] === 'svg' ? node[2] : node) : [];
  landingIcons[key] = kids.map(([tag, attrs]) => `<${tag} ${Object.entries(attrs).map(([k, v]) => `${kebab(k)}="${v}"`).join(' ')}/>`).join('');
}
writeFileSync('assets/landing-icons.json', JSON.stringify(landingIcons));

// --- نشانی نسخه‌دار: ?v=هش محتوا، تا مرورگر فایل‌ها را طولانی‌مدت کش کند و بعد از هر به‌روزرسانی نسخه‌ی تازه را بگیرد ---
let html = readFileSync('index.html', 'utf8');
html = html.replace(/(\.\/assets\/[A-Za-z0-9._-]+\.(?:js|css))(\?v=[a-f0-9]+)?/g, (_, file) => `${file}?v=${createHash('sha256').update(readFileSync(file.slice(2))).digest('hex').slice(0, 10)}`);
writeFileSync('index.html', html);
console.log('build done');
